/** Derive app and monochrome tray assets from the EcoAI transparent master. */
import { app, BrowserWindow, nativeImage } from "electron"
import { Data } from "resedit"
import { readFileSync, writeFileSync } from "node:fs"

const mark = readFileSync(new URL("../packaging/brand/ecoai-mark.png", import.meta.url))
const source = `data:image/png;base64,${mark.toString("base64")}`
const appSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
<rect x="64" y="64" width="896" height="896" rx="200" fill="#f7faf6"/>
<image x="96" y="96" width="832" height="832" href="${source}"/></svg>`

async function render(svg, size) {
  const win = new BrowserWindow({ show: false, width: size, height: size,
    transparent: true, backgroundColor: "#00000000",
    webPreferences: { offscreen: true } })
  try {
    await win.loadURL(`data:text/html;charset=utf-8,${encodeURIComponent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`)}`)
    await win.webContents.executeJavaScript("Promise.all([...document.images].map(i => i.decode()))")
    const image = await win.webContents.capturePage({ x: 0, y: 0, width: size, height: size })
    return image.resize({ width: size, height: size }).toPNG()
  } finally {
    win.destroy()
  }
}

function writeWindowsIcon(png) {
  const image = nativeImage.createFromBuffer(png)
  const ico = new Data.IconFile()
  ico.icons = [16, 24, 32, 48, 64, 128, 256].map(size => ({
    width: size, height: size,
    data: Data.RawIconItem.from(image.resize({ width: size, height: size, quality: "best" }).toPNG(), size, size, 32),
  }))
  writeFileSync("packaging/icon.ico", Buffer.from(ico.generate()))
}

app.on("window-all-closed", () => {})
app.whenReady().then(async () => {
  if (process.argv.includes("--windows-only")) {
    writeWindowsIcon(readFileSync("packaging/icon.png"))
    console.log("Generated EcoAI Windows ICO from the existing app PNG.")
    return
  }
  // macOS supplies the menu-bar color for this monochrome leaf silhouette.
  const image = nativeImage.createFromBuffer(mark).resize({ width: 36, height: 36, quality: "best" })
  const bitmap = image.toBitmap()
  for (let i = 0; i < bitmap.length; i += 4) bitmap.fill(0, i, i + 3)
  const tray = nativeImage.createFromBitmap(bitmap, { width: 36, height: 36 }).toPNG()
  const traySvg = `<svg xmlns="http://www.w3.org/2000/svg" width="36" height="36" viewBox="0 0 36 36"><image width="36" height="36" href="data:image/png;base64,${tray.toString("base64")}"/></svg>`
  writeFileSync("packaging/icon.svg", appSvg + "\n")
  const appPng = await render(appSvg, 1024)
  writeFileSync("packaging/icon.png", appPng)
  writeWindowsIcon(appPng)
  writeFileSync("packaging/tray-icon.svg", traySvg + "\n")
  writeFileSync("packaging/tray-icon.png", tray)
  writeFileSync("src/electron/tray-icon.ts", `// Generated by npm run make-icon from packaging/brand/ecoai-mark.png; monochrome macOS template image.\nexport const 托盘图标 = "data:image/png;base64,${tray.toString("base64")}"\n`)
  console.log("Generated EcoAI app PNG (1024²), Windows ICO (16–256), and transparent tray PNG (36²).")
}).catch(error => {
  console.error(error)
  app.exit(1)
}).finally(() => app.quit())

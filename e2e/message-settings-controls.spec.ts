import { test, expect, 开一段临时会话 } from './fixtures.js'

test('message edit matches copy outline, tone and focus while retaining editing', async ({dawn}, info) => {
  const {page}=dawn
  await 开一段临时会话(page,'对照复制与修改按钮')
  const turn=page.locator('main.main .turn.user').last()
  const copy=turn.getByRole('button',{name:'复制我说的这段',exact:true})
  const edit=turn.getByRole('button',{name:'修改',exact:true})
  await expect(copy).toBeVisible()
  await expect(edit).toBeVisible()
  await page.mouse.move(0,0)
  const styles=await turn.evaluate(el=>['.copy-btn','.edit-btn'].map(selector=>{
    const button=el.querySelector(selector)!, svg=button.querySelector('svg')!
    const b=getComputedStyle(button),s=getComputedStyle(svg),r=button.getBoundingClientRect()
    return {opacity:b.opacity,color:b.color,fill:s.fill,stroke:s.stroke,strokeWidth:s.strokeWidth,viewBox:svg.getAttribute('viewBox'),width:r.width,height:r.height}
  }))
  expect(styles[1]).toEqual(styles[0])
  await page.screenshot({path:info.outputPath('message-actions-light.png')})
  await edit.focus()
  await expect(edit).toHaveCSS('opacity','1')
  await page.screenshot({path:info.outputPath('message-edit-focus.png')})
  await edit.click()
  await expect(page.locator('.turn.editing')).toContainText('上面那句留在原处')
  await page.locator('.turn.editing').getByRole('button',{name:'不改了',exact:true}).click()
  await expect(turn).toContainText('对照复制与修改按钮')
  await page.evaluate(()=>{document.documentElement.classList.remove('dawn-light');document.documentElement.classList.add('dawn-dark')})
  await page.mouse.move(0,0)
  await page.evaluate(()=>(document.activeElement as HTMLElement | null)?.blur())
  await page.screenshot({path:info.outputPath('message-actions-dark.png')})
})

test('settings checkboxes stay compact with label and keyboard controls across surfaces', async ({dawn},info)=>{
  const {page,app}=dawn
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.locator('.settings-column [data-settings-section="notify"]').click()
  const checkbox=page.getByRole('checkbox',{name:'一轮做完',exact:true})
  await expect(checkbox).toBeChecked()
  const size=await checkbox.evaluate(el=>{const r=el.getBoundingClientRect();const label=el.closest('label')!.getBoundingClientRect();return {width:r.width,height:r.height,labelHeight:label.height,offset:Math.abs(r.y+r.height/2-label.y-label.height/2)}})
  expect(size.width).toBe(16)
  expect(size.height).toBe(16)
  expect(size.labelHeight).toBeGreaterThanOrEqual(24)
  expect(size.offset).toBeLessThanOrEqual(1)
  await checkbox.locator('..').getByText('开',{exact:true}).click()
  await expect(checkbox).not.toBeChecked()
  await checkbox.focus()
  await page.keyboard.press('Space')
  await expect(checkbox).toBeChecked()
  await page.screenshot({path:info.outputPath('settings-compact-light.png')})
  const column=page.locator('.settings-column')
  if(await column.isVisible())await column.getByRole('button',{name:'展开',exact:true}).click()
  await page.evaluate(()=>{document.documentElement.classList.remove('dawn-light');document.documentElement.classList.add('dawn-dark')})
  await expect(checkbox).toHaveCSS('width','16px')
  await expect(checkbox).toHaveCSS('height','16px')
  await page.screenshot({path:info.outputPath('settings-full-dark.png')})
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0]!.setSize(900,640))
  await expect(checkbox).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
  await page.screenshot({path:info.outputPath('settings-narrow-dark.png')})
})
